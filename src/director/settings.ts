import { z } from "zod";
export const directorSchema = z.object({
  version: z.literal(1),
  situation: z.enum([
    "live",
    "selfie",
    "friend",
    "office",
    "home",
    "professional",
  ]),
  camera: z.enum([
    "phone-front",
    "phone-rear",
    "super8",
    "vhs",
    "video8",
    "minidv",
    "digital-zoom",
    "cinema",
  ]),
  era: z.enum(["present", "1960s", "1980s", "1990s", "2000s"]),
  operator: z.enum([
    "casual",
    "selfie",
    "friend",
    "observer",
    "home",
    "locked",
    "controlled",
  ]),
  optics: z.enum(["wide", "normal", "zoom", "portrait"]),
  focus: z.enum(["deep", "auto", "manual", "shallow"]),
  color: z.enum(["natural", "video", "warm-film", "graded"]),
  texture: z.enum(["clean", "tape", "dv", "grain"]),
  viewpoint: z.enum(["front", "back", "shoulder"]),
  coverage: z.enum(["single", "second-camera"]),
  intentional: z.boolean(),
});
export type DirectorSettings = z.infer<typeof directorSchema>;
export const defaultDirector: DirectorSettings = {
  version: 1,
  situation: "live",
  camera: "phone-rear",
  era: "present",
  operator: "casual",
  optics: "wide",
  focus: "auto",
  color: "natural",
  texture: "clean",
  viewpoint: "front",
  coverage: "single",
  intentional: false,
};
